"""Spec 037: tables of a three-seed scoring record (validation or test), from readings only.

    uv run python scripts/research/rmis_val_tables.py experiments/<record> [--test]

Reads ``runs/<condition>/reading.json`` (systems, coverage, interval scores),
``reading-ft.json`` (paired ratios with the three fine-tuned seeds pooled) and
``reading-hybrid.json``; writes ``tables.md`` and ``summary.json``.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

FT = ("ft-s1", "ft-s2", "ft-s3")
REG = ("reg-s1", "reg-s2", "reg-s3")
COLS = (("range", "range"), ("course_deg", "course"), ("speed_kt", "speed"))
ORDER = ("off", "all-central", "ho-both", "out-central", "corr-central", "ho-osc", "ho-burst")


def iv(r: dict[str, Any]) -> str:
    if not r.get("scenarios"):
        return "n/a"
    return f"{r['ratio']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}]"


def gm(xs: list[float]) -> float:
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("record")
    a = ap.parse_args()
    rec = Path(a.record)
    conds = [c for c in ORDER if (rec / "runs" / c / "reading.json").exists()]
    R = {c: json.loads((rec / "runs" / c / "reading.json").read_text()) for c in conds}
    F = {c: json.loads((rec / "runs" / c / "reading-ft.json").read_text()) for c in conds}
    out: dict[str, Any] = {
        "conditions": conds,
        "median_range": {},
        "paired": {},
        "coverage": {},
        "hybrid": {},
    }
    names = ["c2-robust", "c2", "robust-true", "plain-true", "imm", "ekf", "one_leg"]
    L = ["# Tables (generated by `scripts/research/rmis_val_tables.py`)", ""]
    L += [f"{R[conds[0]]['scenarios']} engagements per condition.", ""]
    L += ["## Median over engagements of the engagement's median relative range error", ""]
    L += [
        "| Condition | fine-tuned (3) | unchanged (3) | " + " | ".join(names) + " |",
        "|---" * (len(names) + 3) + "|",
    ]
    for c in conds:
        s = R[c]["systems"]
        row = {
            "ft": gm([s[n]["range"]["scenario_median"] for n in FT]),
            "reg": gm([s[n]["range"]["scenario_median"] for n in REG]),
        }
        row |= {n: s[n]["range"]["scenario_median"] for n in names}
        out["median_range"][c] = row
        L.append(
            f"| {c} | {row['ft']:.3f} | {row['reg']:.3f} | "
            + " | ".join(f"{row[n]:.3f}" for n in names)
            + " |"
        )
    for key, label in COLS[1:]:
        L += ["", f"## Efficiency in {label} (against the bound of the scoring run)", ""]
        L += [
            "| Condition | fine-tuned (3) | unchanged (3) | c2-robust | robust-true |",
            "|---|---|---|---|---|",
        ]
        for c in conds:
            s = R[c]["systems"]

            def e(n: str, s: Any = s, key: str = key) -> float:
                return float(s[n][key].get("efficiency", float("nan")))

            L.append(
                f"| {c} | {gm([e(n) for n in FT]):.2f} | {gm([e(n) for n in REG]):.2f} | {e('c2-robust'):.2f} | {e('robust-true'):.2f} |"
            )
    L += [
        "",
        "## Paired per engagement: control ÷ fine-tuned, the three seeds pooled (above 1: fine-tuned better)",
        "",
    ]
    L += [
        "| Condition | Control | Range | n | Median | Better | Twice as good | Twice as bad | Outcome | Course | Speed | Range, each seed |",
        "|---" * 12 + "|",
    ]
    for c in conds:
        out["paired"][c] = {}
        for ctl in ("c2-robust", "c2", "robust-true"):
            p = F[c]["paired"][ctl]
            r = p["range"]["pooled"]
            out["paired"][c][ctl] = {k: p[k]["pooled"] for k, _ in COLS} | {
                "each": {n: p["range"][n] for n in FT}
            }
            L.append(
                f"| {c} | {ctl} | {iv(r)} | {r['scenarios']} | {r['median_ratio']:.2f} | {r['share_better']:.2f} | {r['share_twice_as_good']:.2f} | "
                f"{r['share_twice_as_bad']:.2f} | {r['outcome']} | {iv(p['course_deg']['pooled'])} | {iv(p['speed_kt']['pooled'])} | "
                + ", ".join(f"{p['range'][n]['ratio']:.2f}" for n in FT)
                + " |"
            )
    L += ["", "## Unchanged ÷ fine-tuned, the same training seed (the fine-tune's own effect)", ""]
    L += ["| Condition | Seed | Range | Outcome | Course | Speed |", "|---|---|---|---|---|---|"]
    for c in conds:
        out["paired"][c]["same_seed"] = {}
        for k in (1, 2, 3):
            p = F[c]["paired"][f"reg-s{k}"]
            n = f"ft-s{k}"
            out["paired"][c]["same_seed"][n] = {key: p[key][n] for key, _ in COLS}
            L.append(
                f"| {c} | {k} | {iv(p['range'][n])} | {p['range'][n]['outcome']} | {iv(p['course_deg'][n])} | {iv(p['speed_kt'][n])} |"
            )
    L += [
        "",
        "## Range by true-range third: C″-robust ÷ fine-tuned, pooled (near, middle, far)",
        "",
        "| Condition | Near | Middle | Far |",
        "|---|---|---|---|",
    ]
    for c in conds:
        L.append(
            f"| {c} | "
            + " | ".join(iv(b["pooled"]) for b in F[c]["paired_by_range_band"]["c2-robust"])
            + " |"
        )
    L += ["", "## Coverage of the stated 95% intervals (scales as in the plan)", ""]
    L += [
        "| Condition | System | Range | (norm. error) | Course | stated | (norm. error) | Speed | (norm. error) |",
        "|---" * 9 + "|",
    ]
    for c in conds:
        out["coverage"][c] = {}
        for n in (*FT, "reg-s1"):
            cv = R[c]["coverage"][n]
            out["coverage"][c][n] = {q: cv[q]["all"] for q in cv}

            def g(q: str, k: str, cv: Any = cv) -> float:
                return float(cv[q]["all"][k])

            def ci(q: str, cv: Any = cv) -> str:
                x = cv[q]["all"]
                return f"{x['coverage']:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"

            L.append(
                f"| {c} | {n} | {ci('range')} | {g('range', 'normalised_error_median'):.2f} | {ci('course_deg')} | {g('course_deg', 'stated_share'):.2f} | "
                f"{g('course_deg', 'normalised_error_median'):.2f} | {ci('speed_kt')} | {g('speed_kt', 'normalised_error_median'):.2f} |"
            )
    if any(R[c].get("interval_score") for c in conds):
        L += [
            "",
            "## Interval score: the head ÷ the temperature control (below 1: the head is better)",
            "",
        ]
        L += [
            "| Condition | System | Range | Course | Speed | Control's coverage (range, course, speed) |",
            "|---|---|---|---|---|---|",
        ]
        out["interval_score"] = {}
        for c in conds:
            out["interval_score"][c] = R[c]["interval_score"]
            for n in FT:
                x = R[c]["interval_score"][n]
                tc = R[c]["temperature_coverage"][n]
                L.append(
                    f"| {c} | {n} | {iv(x['range'])} | {iv(x['course_deg'])} | {iv(x['speed_kt'])} | {tc['range']:.3f}, {tc['course_deg']:.3f}, {tc['speed_kt']:.3f} |"
                )
    L += ["", "## The hybrid and the static range-prior comparator", ""]
    L += [
        "| Condition | System | Median range | C″-robust ÷ system: range | Median | Twice as bad | Course | Speed | Fine-tuned (same seed) ÷ system: range | Course | Speed |",
        "|---" * 11 + "|",
    ]
    for c in conds:
        f = rec / "runs" / c / "reading-hybrid.json"
        if not f.exists():
            continue
        H = json.loads(f.read_text())
        out["hybrid"][c] = {}
        for w in sorted(n for n in H["systems"] if n.startswith("hyb-") or n == "c2-prior"):
            pc = H["paired"]["c2-robust"]
            seed = w.split("-")[1] if w.startswith("hyb-") else "s1"
            pf = H["paired"][f"ft-{seed}"]
            r = pc["range"][w]
            out["hybrid"][c][w] = {
                "vs_c2_robust": {k: pc[k][w] for k, _ in COLS},
                "vs_ft": {k: pf[k][w] for k, _ in COLS},
            }
            L.append(
                f"| {c} | {w} | {H['systems'][w]['range']['scenario_median']:.3f} | {iv(r)} | {r['median_ratio']:.2f} | {r['share_twice_as_bad']:.2f} | "
                f"{iv(pc['course_deg'][w])} | {iv(pc['speed_kt'][w])} | {iv(pf['range'][w])} | {iv(pf['course_deg'][w])} | {iv(pf['speed_kt'][w])} |"
            )
        if (
            "pooled" in H["paired"]["c2-robust"]["range"]
            and not (rec / "runs" / c / "hybrid-pooled.skip").exists()
        ):
            out["hybrid"][c]["pooled_all_listed"] = H["paired"]["c2-robust"]["range"]["pooled"]
    (rec / "tables.md").write_text("\n".join(L) + "\n")
    (rec / "summary.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    print(f"wrote {rec / 'tables.md'}")


if __name__ == "__main__":
    main()
