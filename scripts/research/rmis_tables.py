"""Spec 037: tables of a regressor-under-mismatch record, generated from its readings only.

    uv run python scripts/research/rmis_tables.py experiments/<record> [--rule]

Reads ``runs/<condition>/reading.json`` (written by ``tma2-rmread`` in the scoring job) and writes
``tables.md`` and ``summary.json``. With ``--rule`` it applies step 1's rule (``RULE.md``) on the
primary condition. Nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

ORDER = ["off"] + [
    f"{k}-{s}"
    for k in ("corr", "bias", "sigma", "out", "all")
    for s in ("mild", "central", "harsh")
]
SYSTEMS = ["reg", "c2-robust", "c2", "robust-true", "plain-true", "imm", "ekf", "one_leg"]
LABEL = {
    "reg": "regressors (3, unchanged)",
    "c2-robust": "C″, robust final solve",
    "c2": "C″",
    "robust-true": "robust solve, true segmentation",
    "plain-true": "plain solve, true segmentation",
    "imm": "IMM",
    "ekf": "EKF",
    "one_leg": "one leg",
}


def gmean(xs: list[float]) -> float:
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("record")
    ap.add_argument("--rule", action="store_true")
    ap.add_argument("--primary", default="all-central")
    a = ap.parse_args()
    rec = Path(a.record)
    conds = [c for c in ORDER if (rec / "runs" / c / "reading.json").exists()]
    conds += sorted(p.name for p in (rec / "runs").iterdir() if p.name not in ORDER)
    R: dict[str, Any] = {
        c: json.loads((rec / "runs" / c / "reading.json").read_text()) for c in conds
    }
    regs = sorted(n for n in R[conds[0]]["systems"] if n.startswith("reg-"))

    def med(c: str, s: str, col: str = "range", key: str = "scenario_median") -> float:
        if s == "reg":
            return gmean([R[c]["systems"][n][col][key] for n in regs])
        return float(R[c]["systems"][s][col][key])

    out: dict[str, Any] = {
        "conditions": conds,
        "regressors": regs,
        "median_range": {},
        "paired": {},
    }
    L = ["# Tables (generated by `scripts/research/rmis_tables.py`; development data)", ""]
    n = R[conds[0]]["scenarios"]
    L += [f"{n} engagements per condition, the same engagements under each condition.", ""]
    L += ["## Median over engagements of the engagement's median relative range error", ""]
    L += [
        "| Condition | " + " | ".join(LABEL[s] for s in SYSTEMS) + " |",
        "|---" * (len(SYSTEMS) + 1) + "|",
    ]
    for c in conds:
        row = {s: med(c, s) for s in SYSTEMS}
        out["median_range"][c] = row
        L.append(f"| {c} | " + " | ".join(f"{row[s]:.3f}" for s in SYSTEMS) + " |")
    for col, name in (("course_deg", "course"), ("speed_kt", "speed")):
        L += ["", f"## Efficiency in {name} (median error ÷ bound ÷ 0.6745)", ""]
        L += ["| Condition | " + " | ".join(LABEL[s] for s in SYSTEMS[:5]) + " |", "|---" * 6 + "|"]
        for c in conds:
            L.append(
                f"| {c} | "
                + " | ".join(f"{med(c, s, col, 'efficiency'):.2f}" for s in SYSTEMS[:5])
                + " |"
            )
    for ctl in ("c2-robust", "c2", "robust-true"):
        L += [
            "",
            f"## {LABEL[ctl]} ÷ regressors, paired per engagement (above 1: the regressors are better)",
            "",
        ]
        L += [
            "| Condition | Range, pooled | n | Median ratio | Better | Twice as good | Twice as bad | Outcome | Course, pooled | Speed, pooled |",
            "|---" * 10 + "|",
        ]
        out["paired"][ctl] = {}
        for c in conds:
            p = R[c]["paired"][ctl]
            r, cs, sp = (p[k]["pooled"] for k in ("range", "course_deg", "speed_kt"))
            out["paired"][ctl][c] = {"range": r, "course": cs, "speed": sp}
            L.append(
                f"| {c} | {r['ratio']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}] | {r['scenarios']} | {r['median_ratio']:.2f} | "
                f"{r['share_better']:.2f} | {r['share_twice_as_good']:.2f} | {r['share_twice_as_bad']:.2f} | {r['outcome']} | "
                f"{cs['ratio']:.2f} [{cs['lo']:.2f}, {cs['hi']:.2f}] | {sp['ratio']:.2f} [{sp['lo']:.2f}, {sp['hi']:.2f}] |"
            )
    L += [
        "",
        "## C″-robust ÷ regressors in range, by true-range third (near, middle, far), pooled",
        "",
    ]
    L += ["| Condition | Near | Middle | Far |", "|---|---|---|---|"]
    for c in conds:
        bands = [b["pooled"] for b in R[c]["paired_by_range_band"]["c2-robust"]]
        L.append(
            f"| {c} | "
            + " | ".join(f"{b['ratio']:.2f} [{b['lo']:.2f}, {b['hi']:.2f}]" for b in bands)
            + " |"
        )
    L += [
        "",
        "## Coverage of the stated 95% intervals (variance head, scale as in the plan), mean of the three regressors",
        "",
    ]
    L += [
        "| Condition | Range | (normalised error) | Course | stated share | (normalised error) | Speed | (normalised error) |",
        "|---" * 8 + "|",
    ]
    out["coverage"] = {}
    for c in conds:
        cov = R[c]["coverage"]

        def m(col: str, key: str, cov: Any = cov) -> float:
            return sum(cov[n][col]["all"][key] for n in regs) / len(regs)

        out["coverage"][c] = {
            col: {k: m(col, k) for k in ("coverage", "normalised_error_median", "stated_share")}
            for col in ("range", "course_deg", "speed_kt")
        }
        L.append(
            f"| {c} | {m('range', 'coverage'):.3f} | {m('range', 'normalised_error_median'):.2f} | {m('course_deg', 'coverage'):.3f} | "
            f"{m('course_deg', 'stated_share'):.2f} | {m('course_deg', 'normalised_error_median'):.2f} | {m('speed_kt', 'coverage'):.3f} | {m('speed_kt', 'normalised_error_median'):.2f} |"
        )
    L += [
        "",
        "## Share of rows answered",
        "",
        "| Condition | " + " | ".join(LABEL[s] for s in SYSTEMS[1:]) + " |",
        "|---" * len(SYSTEMS) + "|",
    ]
    for c in conds:
        L.append(
            f"| {c} | "
            + " | ".join(f"{R[c]['systems'][s]['answered']:.2f}" for s in SYSTEMS[1:])
            + " |"
        )
    if a.rule:
        A = med(a.primary, "reg") / med("off", "reg")
        B = R[a.primary]["paired"]["c2-robust"]["range"]["pooled"]
        holds = A <= 1.10 and B["lo"] > 1
        out["rule"] = {"A": A, "B": B, "holds_up": holds, "primary": a.primary}
        L += ["", "## The rule (RULE.md)", ""]
        L += [
            f"- A = {A:.2f} (the regressors' error under `{a.primary}` ÷ their error with mismatch off; holds up needs at most 1.10)."
        ]
        L += [
            f"- B = {B['ratio']:.3f} [{B['lo']:.3f}, {B['hi']:.3f}] (C″-robust ÷ regressors, pooled; holds up needs the interval above 1)."
        ]
        L += [
            f"- **{'Holds up: no fine-tune for robustness; ask the owner.' if holds else 'Does not hold up: step 2 proceeds.'}**"
        ]
    (rec / "tables.md").write_text("\n".join(L) + "\n")
    (rec / "summary.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    print(f"wrote {rec / 'tables.md'}")


if __name__ == "__main__":
    main()
