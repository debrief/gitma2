"""Spec 038: a record's tables.md and summary.json from its runs' decomp.json files.

    uv run python scripts/research/gd_tables.py experiments/<record>

Every number in tables.md comes from ``runs/<split>/<condition>/decomp.json`` (written by
tma2-rdecomp in the scoring job) or, for the differences between splits, from the
per-engagement log ratios in ``decomp-logs.npz``. Nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

import numpy as np

COLS = ("range", "course_deg", "speed_kt")
HOLD = math.log(1.15)


def iv(r: dict[str, Any] | None, key: str = "ratio") -> str:
    if not r or key not in r:
        return "—"
    return f"{r[key]:.3f} [{r['lo']:.3f}, {r['hi']:.3f}]"


def dist(r: dict[str, Any] | None) -> str:
    if not r or "median_ratio" not in r:
        return "—"
    return (
        f"{r['median_ratio']:.2f}; {r['share_better']:.2f} / {r['share_twice_as_good']:.2f} / "
        f"{r['share_twice_as_bad']:.2f}"
    )


def slice_row(lines: list[str], label: str, blk: dict[str, Any], n: Any) -> None:
    cells = [iv(blk["ratios"][c].get("fine_tuned")) for c in COLS]
    lines.append(f"| {label} | {n} | {' | '.join(cells)} |")


def split_difference(
    a: dict[str, np.ndarray], b: dict[str, np.ndarray], col: str, resamples: int = 2000
) -> dict[str, Any]:
    """mean ln ratio on split b minus on split a (different engagements: independent draws)."""
    x, y = a[f"log_{col}"], b[f"log_{col}"]
    rng = np.random.default_rng(43)
    dx = x[rng.integers(0, x.size, (resamples, x.size))].mean(axis=1)
    dy = y[rng.integers(0, y.size, (resamples, y.size))].mean(axis=1)
    lo, hi = (float(v) for v in np.quantile(dy - dx, [0.025, 0.975]))
    d = float(y.mean() - x.mean())
    out = "shrinks" if hi < 0 else "grows" if lo > 0 else "not separated"
    if -HOLD <= lo and hi <= HOLD:
        out = "holds"
    return {"difference": d, "lo": lo, "hi": hi, "factor": math.exp(d), "outcome": out}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("record")
    a = ap.parse_args()
    rec = Path(a.record)
    runs: dict[tuple[str, str], dict[str, Any]] = {}
    logs: dict[tuple[str, str], dict[str, np.ndarray]] = {}
    for p in sorted(rec.glob("runs/*/*/decomp.json")):
        key = (p.parts[-3], p.parts[-2])
        runs[key] = json.loads(p.read_text())
        lp = p.with_name("decomp-logs.npz")
        if lp.exists():
            with np.load(lp) as z:
                logs[key] = {k: z[k] for k in z.files}
    if not runs:
        raise SystemExit(f"no runs under {rec}/runs")
    L: list[str] = [
        "# Tables",
        "",
        "Generated by `scripts/research/gd_tables.py` from the runs' `decomp.json`. Ratios are "
        "the comparator ÷ the system per engagement (above 1: the system is better), geometric "
        'mean with a 95% engagement-bootstrap interval. "Distribution" is the median ratio; '
        "the shares better / twice as good / twice as bad.",
        "",
    ]
    summary: dict[str, Any] = {"runs": {}, "split_differences": {}}
    for (split, cond), r in runs.items():
        cmp_ = r["names"]["comparator"]
        tag = f"{split} / {cond}"
        summary["runs"][tag] = {k: r[k] for k in ("all", "rows", "scenarios", "absent") if k in r}
        L += [f"## {tag} ({r['scenarios']} engagements, {r['rows']} rows)", ""]
        L += [
            f"### {cmp_} ÷ system",
            "",
            "| system | range | distribution | course | speed | n |",
            "|---|---|---|---|---|---|",
        ]
        for g, x in r["all"]["ratios"]["range"].items():
            c, s = r["all"]["ratios"]["course_deg"].get(g), r["all"]["ratios"]["speed_kt"].get(g)
            L.append(f"| {g} | {iv(x)} | {dist(x)} | {iv(c)} | {iv(s)} | {x.get('scenarios', 0)} |")
        L += [
            "",
            "### classical challenger ÷ fine-tuned regressor",
            "",
            "| control | range | distribution | course | speed |",
            "|---|---|---|---|---|",
        ]
        for g, x in r["all"]["versus"]["range"].items():
            c, s = r["all"]["versus"]["course_deg"].get(g), r["all"]["versus"]["speed_kt"].get(g)
            L.append(f"| {g} | {iv(x)} | {dist(x)} | {iv(c)} | {iv(s)} |")
        for kind, title in (
            ("gap_closed", "Share of the gap to the fine-tuned regressor closed"),
            ("prior_share", "Share of the fine-tuned regressor's gain obtained by the prior"),
        ):
            L += [
                "",
                f"### {title}",
                "",
                "| system | range | course | speed | outcome (range) |",
                "|---|---|---|---|---|",
            ]
            for g, x in r["all"][kind]["range"].items():
                cells = []
                for col in COLS:
                    y = r["all"][kind][col].get(g, {})
                    cells.append(iv(y, "share") if y.get("defined") else "not defined")
                L.append(f"| {g} | {' | '.join(cells)} | {x.get('outcome', '—')} |")
        L += [
            "",
            "### Absolute errors (median over engagements of the engagement median) and efficiency",
            "",
            "| system | answered | range | course ° | speed kt | efficiency range / course / speed |",
            "|---|---|---|---|---|---|",
        ]
        for n, x in r["systems"].items():
            eff = " / ".join(f"{x[c].get('efficiency', math.nan):.2f}" for c in COLS)
            L.append(
                f"| {n} | {x['answered']:.3f} | {x['range']['scenario_median']:.4f} | "
                f"{x['course_deg']['scenario_median']:.2f} | {x['speed_kt']['scenario_median']:.2f} | {eff} |"
            )
        L += [
            "",
            f"### Slices: {cmp_} ÷ fine-tuned (range; course; speed)",
            "",
            "| slice | n | range | course | speed |",
            "|---|---|---|---|---|",
        ]

        slice_row(L, "rows every system answers", r["common_rows"], r["common_rows"]["rows"])
        bands = ["under 5 min", "5 to 15 min", "over 15 min"]
        for b, blk in enumerate(r["slices"].get("since_change", [])):
            slice_row(L, f"since the last target change: {bands[b]}", blk, f"{blk['rows']} rows")
        for v, blk in r["slices"].get("first_bearing_wild", {}).items():
            slice_row(L, f"first bearing an outlier: {v}", blk, blk["scenarios"])
        st = r["slices"].get("structure_at_first_row")
        if st:
            for label in ("right", "wrong"):
                if label in st:
                    slice_row(
                        L,
                        f"C″'s structure {label} at the first scored row (later rows)",
                        st[label],
                        st[label]["scenarios"],
                    )
            L.append("")
            L.append(
                f"C″'s structure was right at the first scored row in {st['right_share']:.2f} of {st['classified']} engagements (match tolerance {st['match_tolerance_s']:.0f} s)."
            )
        if "by_bound_third" in r:
            L += [
                "",
                "### Efficiency by thirds of the bound (tight, middle, loose)",
                "",
                "| system | range | course | speed |",
                "|---|---|---|---|",
            ]
            for n in r["by_bound_third"]["range"]["thirds"][0]:
                cells = [
                    " / ".join(
                        f"{t[n].get('efficiency', math.nan):.2f}"
                        for t in r["by_bound_third"][c]["thirds"]
                    )
                    for c in COLS
                ]
                L.append(f"| {n} | {' | '.join(cells)} |")
        L.append("")
    base_splits = sorted({s for s, _ in logs})
    if "in" in base_splits and len(base_splits) > 1:
        L += [
            "## Differences between splits",
            "",
            'ln(comparator ÷ fine-tuned) on the split minus in distribution, as a factor; "holds" within ±15%, "shrinks" wholly below 1.',
            "",
            "| split | condition | range | course | speed |",
            "|---|---|---|---|---|",
        ]
        for (split, cond), lg in logs.items():
            if split == "in" or ("in", cond) not in logs:
                continue
            cells = []
            for col in COLS:
                d = split_difference(logs[("in", cond)], lg, col)
                summary["split_differences"][f"{split}/{cond}/{col}"] = d
                cells.append(
                    f"{d['factor']:.3f} [{math.exp(d['lo']):.3f}, {math.exp(d['hi']):.3f}] {d['outcome']}"
                )
            L.append(f"| {split} | {cond} | {' | '.join(cells)} |")
        L.append("")
    (rec / "tables.md").write_text("\n".join(L) + "\n")
    (rec / "summary.json").write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n")
    print(f"wrote {rec}/tables.md ({len(runs)} runs)")


if __name__ == "__main__":
    main()
