"""Tables for a spec 025 record, generated from its ``summary.json`` (never hand-copied).

    uv run python scripts/research/tl8_tables.py experiments/<record>

Writes ``<record>/tables.md``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

QUANT = ("range", "course", "speed")
COMPARISONS = {
    "alone/joint": "`ctl` alone ÷ joint (the decided ratio; above 1: joining helps)",
    "full/joint": "every bearing ÷ joint (below 1: what the gaps cost)",
    "joint/ref-span": "joint ÷ the true history across the span (what is left)",
    "c2/joint": "C″ per period ÷ joint",
    "alone/ref-alone": "`ctl` alone ÷ the true history per period",
    "one-leg/joint": "one leg per period ÷ joint",
}
KINDS = (
    "own_turn",
    "no_own_turn",
    "gap_under_10min",
    "gap_10_to_20min",
    "gap_over_20min",
    "gap_manoeuvre",
    "no_gap_manoeuvre",
    "span_bound_tight",
    "span_bound_middle",
    "span_bound_loose",
)


def _r(d: dict[str, Any]) -> str:
    if not d or "value" not in d:
        return "—"
    return f"{d['value']:.2f} [{d['lo']:.2f}, {d['hi']:.2f}]"


def _shares(d: dict[str, Any]) -> str:
    if not d or "value" not in d:
        return "—"
    return (
        f"{d['median']:.2f} | {d['better']:.2f} | {d['twice_as_good']:.2f} | "
        f"{d['twice_as_bad']:.2f} | {d['periods']} / {d['engagements']}"
    )


def tables(summary: dict[str, Any]) -> str:
    out = [
        "# Tables",
        "",
        f"Generated by `scripts/research/tl8_tables.py` from `summary.json` (plan "
        f"`{summary['plan']}`, digest `{summary['plan_sha256'][:8]}…`).",
        "",
        "Ratios are geometric means of per-period ratios of period median error, with 95% "
        "intervals from resampling engagements. Rows: each period's own rows 30 s apart where "
        "the known-history bound from the span's bearings is below 0.5.",
        "",
    ]
    sp = summary["splits"]
    out += [
        "## Counts",
        "",
        "| split | engagements | skipped | periods | scored | "
        "fell back | rows | rows (own bound) | verdict |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s, r in sp.items():
        out.append(
            f"| {s} | {r['engagements']} | {r['engagements_skipped']} | {r['periods']} | "
            f"{r['periods_scored']} | {r['joint_fell_back']} | {r['scored_rows']} | "
            f"{r['scored_rows_own']} | {r['verdict']['outcome']} |"
        )
    for c, label in COMPARISONS.items():
        out += ["", f"## {label}", "", "| split | range | course | speed |", "|---|---|---|---|"]
        for s, r in sp.items():
            d = r["ratios"].get(c, {})
            out.append(f"| {s} | " + " | ".join(_r(d.get(q, {})) for q in QUANT) + " |")
    out += [
        "",
        "## `ctl` alone ÷ joint in range: median per-period ratio and shares",
        "",
        "| split | median | better | twice as good | twice as bad | periods / engagements |",
        "|---|---|---|---|---|---|",
    ]
    for s, r in sp.items():
        out.append(f"| {s} | {_shares(r['ratios'].get('alone/joint', {}).get('range', {}))} |")
    out += [
        "",
        "## `ctl` alone ÷ joint on rows the period determines alone (own bound below 0.5)",
        "",
        "| split | range | course | speed |",
        "|---|---|---|---|",
    ]
    for s, r in sp.items():
        d = r["ratios_own_rows"].get("alone/joint", {})
        out.append(f"| {s} | " + " | ".join(_r(d.get(q, {})) for q in QUANT) + " |")
    out += ["", "## `ctl` alone ÷ joint in range, by kind of period", ""]
    out += ["| kind | " + " | ".join(sp) + " |", "|---" * (len(sp) + 1) + "|"]
    for k in KINDS:
        cells = []
        for r in sp.values():
            b = r["by_kind"].get(k, {})
            d = b.get("alone/joint", {}).get("range", {})
            cells.append(f"{_r(d)} (n {b.get('periods', 0)})")
        out.append(f"| {k} | " + " | ".join(cells) + " |")
    out += [
        "",
        "## Manoeuvres in gaps (joint solve)",
        "",
        "| split | gaps | with a true manoeuvre | found | missed | invented (share of quiet gaps) |",
        "|---|---|---|---|---|---|",
    ]
    for s, r in sp.items():
        g = r["gaps"]
        inv = g["invented_share"]
        out.append(
            f"| {s} | {g['gaps']} | {g['with_true_manoeuvre']} | {g['found']} | {g['missed']} | "
            f"{g['invented']} ({'—' if inv is None else f'{inv:.2f}'}) |"
        )
    out += [
        "",
        "## Any manoeuvre declared, share of engagements (on held course: false manoeuvres)",
        "",
        "| split | engagements | alone (any period) | joint | joint in a period | joint in a gap "
        "| every bearing |",
        "|---|---|---|---|---|---|---|",
    ]
    for s, r in sp.items():
        f = r["false_manoeuvres"]
        out.append(
            f"| {s} | {f['engagements']} | {f['alone_any']:.2f} | {f['joint_any']:.2f} | "
            f"{f['joint_in_period']:.2f} | {f['joint_in_gap']:.2f} | {f['full_any']:.2f} |"
        )
    out += [
        "",
        "## Range efficiency (median error ÷ span bound ÷ 0.6745) on the scored rows",
        "",
        "| split | " + " | ".join(COMPARISONS_SYSTEMS) + " |",
        "|---" * (len(COMPARISONS_SYSTEMS) + 1) + "|",
    ]
    for s, r in sp.items():
        e = r["efficiency_span_bound"]
        cells = []
        for k in COMPARISONS_SYSTEMS:
            v = e.get(k, {}).get("range")
            cells.append("—" if v is None else f"{v:.2f}")
        out.append(f"| {s} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


COMPARISONS_SYSTEMS = ("alone", "joint", "full", "ref-span", "ref-alone", "c2", "one-leg")


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    rec = Path(args[0])
    summary = json.loads((rec / "summary.json").read_text())
    (rec / "tables.md").write_text(tables(summary))
    print(f"wrote {rec / 'tables.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
