"""Spec 037: summary tables of a one-regressor development record (readings only).

    uv run python scripts/research/rmis_pilot_summary.py experiments/<record> --ft ft-s1 --reg reg-s1

Writes ``tables.md`` from ``runs/<condition>/reading.json`` and ``reading-hybrid.json``.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

COLS = (("range", "range"), ("course_deg", "course"), ("speed_kt", "speed"))


def iv(r: dict[str, Any]) -> str:
    return f"{r['ratio']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}]"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("record")
    ap.add_argument("--ft", default="ft-s1")
    ap.add_argument("--reg", default="reg-s1")
    a = ap.parse_args()
    rec = Path(a.record)
    conds = [
        c for c in ("off", "all-central", "ho-both") if (rec / "runs" / c / "reading.json").exists()
    ]
    R = {c: json.loads((rec / "runs" / c / "reading.json").read_text()) for c in conds}
    names = [a.ft, a.reg, "c2-robust", "c2", "robust-true", "plain-true", "imm", "ekf", "one_leg"]
    L = ["# Tables (generated by `scripts/research/rmis_pilot_summary.py`; development data)", ""]
    L += [f"{R[conds[0]]['scenarios']} engagements per condition (the same engagements).", ""]
    L += ["## Median over engagements of the engagement's median relative range error", ""]
    L += ["| Condition | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    for c in conds:
        L.append(
            f"| {c} | "
            + " | ".join(f"{R[c]['systems'][n]['range']['scenario_median']:.3f}" for n in names)
            + " |"
        )
    for key, label in COLS[1:]:
        L += [
            "",
            f"## Efficiency in {label}",
            "",
            "| Condition | " + " | ".join(names[:6]) + " |",
            "|---" * 7 + "|",
        ]
        for c in conds:
            L.append(
                f"| {c} | "
                + " | ".join(
                    f"{R[c]['systems'][n][key].get('efficiency', float('nan')):.2f}"
                    for n in names[:6]
                )
                + " |"
            )
    L += ["", f"## Paired per engagement: control ÷ {a.ft} (above 1: {a.ft} is better)", ""]
    L += [
        "| Condition | Control | Range | Median | Better | Twice as good | Twice as bad | Course | Speed |",
        "|---" * 9 + "|",
    ]
    for c in conds:
        for ctl in ("c2-robust", "c2", a.reg, "robust-true"):
            p = R[c]["paired"][ctl]
            r = p["range"][a.ft]
            L.append(
                f"| {c} | {ctl} | {iv(r)} | {r['median_ratio']:.2f} | {r['share_better']:.2f} | {r['share_twice_as_good']:.2f} | "
                f"{r['share_twice_as_bad']:.2f} | {iv(p['course_deg'][a.ft])} | {iv(p['speed_kt'][a.ft])} |"
            )
    L += [
        "",
        "## Coverage of the stated 95% intervals (variance head, scale 1, nothing fitted)",
        "",
    ]
    L += [
        "| Condition | System | Range | (norm. error) | Course | stated | (norm. error) | Speed | (norm. error) |",
        "|---" * 9 + "|",
    ]
    for c in conds:
        for n in (a.ft, a.reg):
            cv = R[c]["coverage"][n]

            def g(q: str, k: str, cv: Any = cv) -> float:
                return float(cv[q]["all"][k])

            L.append(
                f"| {c} | {n} | {g('range', 'coverage'):.3f} [{g('range', 'lo'):.3f}, {g('range', 'hi'):.3f}] | {g('range', 'normalised_error_median'):.2f} | "
                f"{g('course_deg', 'coverage'):.3f} | {g('course_deg', 'stated_share'):.2f} | {g('course_deg', 'normalised_error_median'):.2f} | "
                f"{g('speed_kt', 'coverage'):.3f} | {g('speed_kt', 'normalised_error_median'):.2f} |"
            )
    L += [
        "",
        "## The hybrid (C″'s segmentation, robust solve, the regressor as a prior), by prior weight",
        "",
    ]
    L += [
        "| Condition | Weight | Median range | C″-robust ÷ hybrid: range | Median | Twice as bad | Course | Speed | Regressor ÷ hybrid: range | Course | Speed |",
        "|---" * 11 + "|",
    ]
    for c in conds:
        f = rec / "runs" / c / "reading-hybrid.json"
        if not f.exists():
            continue
        H = json.loads(f.read_text())
        for w in sorted(
            (n for n in H["systems"] if n.startswith("hyb-")),
            key=lambda n: float(n.rsplit("w", 1)[1]),
        ):
            pc, pf = H["paired"]["c2-robust"], H["paired"][a.ft]
            r = pc["range"][w]
            L.append(
                f"| {c} | {w.rsplit('w', 1)[1]} | {H['systems'][w]['range']['scenario_median']:.3f} | {iv(r)} | {r['median_ratio']:.2f} | "
                f"{r['share_twice_as_bad']:.2f} | {iv(pc['course_deg'][w])} | {iv(pc['speed_kt'][w])} | {iv(pf['range'][w])} | "
                f"{iv(pf['course_deg'][w])} | {iv(pf['speed_kt'][w])} |"
            )
    (rec / "tables.md").write_text("\n".join(L) + "\n")
    print(f"wrote {rec / 'tables.md'}")


if __name__ == "__main__":
    main()
